import { chromium } from 'playwright';
import { createStatic, attachGameServer } from '../server.js';
const D = '/private/tmp/claude-501/-Users-ismoil-Desktop-game/d6b86078-6f3f-4632-b4d0-25766dfeb358/scratchpad/';
const srv = createStatic(3222); attachGameServer(srv); await new Promise(r => srv.listen(3222, r));
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 800, height: 450 } });
p.on('console', m => { const t = m.text(); if (!/GL Driver|GPU stall|PCFSoft/.test(t)) console.log('[console]', m.type(), t.slice(0, 300)); });
p.on('pageerror', e => console.log('[pageerror]', e.message, (e.stack || '').split('\n').slice(0, 4).join(' | ')));
const t0 = Date.now();
await p.goto('http://localhost:3222/?manual');
await p.waitForSelector('#menu.on', { timeout: 180000 });
console.log('menu ready after', ((Date.now() - t0) / 1000).toFixed(1), 's');
const tick = (n, dt = 1 / 60, render = false) => p.evaluate(([n, dt, render]) => { for (let i = 0; i < n; i++) window.__game.tick(dt, render && i === n - 1); }, [n, dt, render]);
await tick(3, 1 / 60, true);
await p.screenshot({ path: D + 'shot_menu.png' });
await p.click('#btnSolo');
await tick(30, 1 / 60, true);
await p.screenshot({ path: D + 'shot_lobby.png' });
await p.click('#btnPick');
await p.evaluate(() => document.getElementById('btnStart').click());
await tick(60 * 3, 1 / 60, true);
await p.screenshot({ path: D + 'shot_count.png' });
await tick(60 * 3.5, 1 / 60, false);
await p.keyboard.down('KeyW');
await tick(60 * 3, 1 / 60, false);
await p.keyboard.press('KeyE');
await tick(60 * 4, 1 / 60, true);
await p.screenshot({ path: D + 'shot_race1.png' });
const st = () => p.evaluate(() => { const g = window.__game, v = g.race.me.v; return { speed: +(v.speed * 3.6).toFixed(0), gear: v.gear, rpm: +v.rpm.toFixed(2), x: +v.x.toFixed(0), z: +v.z.toFixed(0), phase: g.race.phase, rank: g.race.me.rank, lap: g.race.me.lapCross, surface: v.surface, d: +v.nearest.d.toFixed(1) }; });
console.log('state', JSON.stringify(await st()));
await b.close(); srv.close();
